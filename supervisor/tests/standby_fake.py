    # --- the host's state -----------------------------------------------------------------------------

    def mountinfo(self) -> str:
        text = mountinfo_line(20, "/proc", "proc", "proc") + mountinfo_line(21, "/sys", "sysfs", "sysfs")
        text += mountinfo_line(22, "/dev", "devtmpfs", "udev") + mountinfo_line(23, "/run", "tmpfs", "tmpfs")
        if self.on_card_root:
            text += mountinfo_line(1, "/", "btrfs", f"/dev/{self.card}p2", "rw,compress=zstd:1")
        else:
            text += mountinfo_line(1, "/", "ext4", f"/dev/{self.emmc}p1", "rw,errors=remount-ro,commit=600")
        text += mountinfo_line(24, "/tmp", "tmpfs", "tmpfs")
        text += mountinfo_line(25, "/mnt/pools/data", "btrfs", "/dev/sda", "rw,space_cache=v2")
        text += mountinfo_line(26, "/run/docker/netns/abc", "nsfs", "nsfs")
        if BOOT_DIR in self.mounted:
            text += mountinfo_line(30, BOOT_DIR, "vfat", f"/dev/{self.card}p1")
        if CARD_DIR in self.mounted:
            text += mountinfo_line(31, CARD_DIR, "btrfs", f"/dev/{self.card}p2", "rw,compress=zstd:1")
        for line in self.extra_mounts:
            text += line
        return text

    def read_cards(self) -> list[MmcCard]:
        return [self.emmc_card, *self.cards]

    def armed_card(self) -> None:
        """The card as Set up the standby leaves it: labelled, mounted, with its first generation."""
        self.cards = [replace(self.cards[0], use="The SD card standby", labels=("UNOS-BOOT", "UNOS-STANDBY"),
                              mounted=True, uuids=frozenset({BOOT_UUID.lower(), CARD_UUID}))]
        self.mounted = {BOOT_DIR, CARD_DIR}
        self.block_devices |= {f"/dev/{self.card}p1", f"/dev/{self.card}p2"}
        self.uuids = {f"/dev/{self.card}p1": BOOT_UUID, f"/dev/{self.card}p2": CARD_UUID}
        self.files["/etc/fstab"] = EMMC_FSTAB + (
            "# unos-standby: the SD card standby's FAT partition and btrfs top level (managed by UNOS)\n"
            f"UUID={BOOT_UUID} {BOOT_DIR} vfat defaults,noatime,nofail 0 0\n"
            f"UUID={CARD_UUID} {CARD_DIR} btrfs defaults,noatime,nofail,compress=zstd:1,subvolid=5 0 0\n")
        self.dirs |= {BOOT_DIR, CARD_DIR, f"{BOOT_DIR}/unos"}

    def with_generation(self, number: int = 1, *, sync_digests_from: dict | None = None) -> None:
        """A complete generation ``number`` as a sync leaves it."""
        self.subvolumes[number] = self.next_subvolume_id
        self.next_subvolume_id += 1
        self.files[f"{BOOT_DIR}/unos/current.txt"] = (
            f"unos_gen={number}\nunos_subvolid={self.subvolumes[number]}\nunos_bootdir=unos/boot-{number}/\n")
        self.dirs.add(f"{BOOT_DIR}/unos/boot-{number}")
        for key, value in (sync_digests_from or {}).items():
            self.files[key.replace("@sys-N", f"@sys-{number}")] = value

    def counts_tries_unanswered(self) -> bool:
        """Whether a boot would run the card's chooser while the eMMC lacks the enabled unit that sets its
        tries counter back to 0: each boot then counts a try that nothing resets, and the fourth boots the
        card's root (ADR-0494). The chooser runs while the card's FAT partition (labelled UNOS-BOOT) holds
        boot.scr, mounted or not, whichever loader the boot ROM took."""
        chooser = any("UNOS-BOOT" in card.labels for card in self.cards) and (
            f"{BOOT_DIR}/boot.scr" in self.files or f"{BOOT_DIR}/boot.scr" in self.hidden.get(BOOT_DIR, {}))
        unit = "unos-standby-boot-ok.service"
        reset = (unit in self.enabled and f"/etc/systemd/system/{unit}" in self.files
                 and "/usr/local/lib/unos-standby/unos-standby-boot-ok.sh" in self.files)
        return chooser and not reset

    def sectors_written(self) -> str:
        return " ".join(["1", "0", "2", "0", "3", "0", str(self.card_sectors_written), "0", "0", "0", "0"])

    def exists(self, path: str) -> bool:
        if path in self.files or path in self.dirs or path in self.block_devices:
            return True
        if path == "/dev/watchdog0":
            return self.watchdog
        match = re.fullmatch(rf"{re.escape(CARD_DIR)}/@sys-([0-9]+)(/.*)?", path)
        if match and int(match.group(1)) in self.subvolumes:
            return match.group(2) is None
        return any(name.startswith(path.rstrip("/") + "/") for name in [*self.files, *self.dirs])

    # --- the commands --------------------------------------------------------------------------------

    def run(self, cmd, *, timeout=60, check=False, input=None, errors=None):
        cmd = list(cmd)
        self.calls.append(cmd)
        if cmd[0] == "systemd-run" and "--unit=unos-standby-return" in cmd:
            # The return to the eMMC's unit (system.sd-standby-failback): started, it runs on its own.
            self._change(cmd)
            return host.HostResult(0, "", "")
        if cmd[0] == "systemd-run":
            assert "--wait" in cmd and "--pipe" in cmd and any(part.startswith("--unit=unos-standby-sync") for part in cmd)
            inner = cmd[cmd.index("--") + 1:]
            self.unit_calls.append(inner)
            result = self._answer(inner, input)
        else:
            result = self._answer(cmd, input)
        if check and not result.ok:
            raise host.HostCommandError(cmd, result.returncode, result.stderr)
        return result

    def _change(self, cmd: list[str]) -> None:
        if self.cut_at is not None and len(self.changes) >= self.cut_at:
            raise PowerCut(cmd)
        self.changes.append(cmd)
        if any(part.startswith(("/mnt/.unos-standby", f"of=/dev/{self.card}", f"/dev/{self.card}")) for part in cmd):
            self.card_sectors_written += 2048

    def _answer(self, cmd: list[str], input: str | None) -> host.HostResult:
        ok, fail = host.HostResult(0, "", ""), host.HostResult(1, "", f"{cmd[0]}: failed\n")
        program = cmd[0]
        if program == "cat" and cmd[1] == "--":
            path = cmd[2]
            if path == "/proc/1/mountinfo":
                return host.HostResult(0, self.mountinfo(), "")
            return host.HostResult(0, self.files[path], "") if path in self.files else fail
        if program == "test":
            if cmd[1] == "-b":
                return ok if cmd[2] in self.block_devices else fail
            return ok if self.exists(cmd[2]) else fail
        if program == "du":
            paths = cmd[cmd.index("--") + 1:]
            excludes = [part[len("--exclude="):] for part in cmd if part.startswith("--exclude=")]
            lines = [f"{size}\t{path}\n" for path in paths if (size := self.size_of(path, excludes)) is not None]
            return host.HostResult(0 if len(lines) == len(paths) else 1, "".join(lines), "")
        if program == "df":
            return host.HostResult(0, f"  1B-blocks     Avail\n{self.card_df[0]} {self.card_df[1]}\n", "")
        if program == "stat" and cmd[1:3] == ["-c", "%i"]:
            path = cmd[-1]
            if not self.exists(path):
                return fail
            return host.HostResult(0, "256\n" if path in self.subvolume_paths else "4711\n", "")
        if program == "stat":
            path = cmd[-1]
            return host.HostResult(0, f"{self.sizes[path]}\n", "") if path in self.sizes else fail
        if program == "/bin/sh" and "command -v" in cmd[2]:
            return host.HostResult(0, "".join(f"{name}\n" for name in self.missing_tools if name in cmd[4:]), "")
        if program == "/bin/sh" and "unos-write" in cmd:
            path = cmd[cmd.index("unos-write") + 1]
            self._change(["write", path])
            self.files[path] = input or ""
            return ok
        if program == "docker":
            return self._docker(cmd)
        if program == "sha256sum":
            if cmd[-1] not in self.files:
                return fail
            data = self.files[cmd[-1]].encode("utf-8", "surrogateescape")
            return host.HostResult(0, f"{hashlib.sha256(data).hexdigest()}  {cmd[-1]}\n", "")
        if program == "dpkg-query" and cmd[1] == "-S":
            # Armbian's loader package installs a folder of another name (ADR-0488).
            owned = cmd[2].startswith(self.loader_dir + "/") and cmd[2] in self.sizes
            return host.HostResult(0, f"{self.loader_package}: {cmd[2]}\n", "") if owned else fail
        if program == "dpkg-query":
            known = cmd[-1] == self.loader_package and self.loader_version
            return host.HostResult(0, self.loader_version, "") if known else fail
        if program == "lsblk":
            assert cmd[-1] == f"/dev/{self.emmc}", cmd
            return host.HostResult(0, json.dumps({"blockdevices": [{"path": f"/dev/{self.emmc}", "uuid": None, "partuuid": None,
                "label": None, "children": [{"path": f"/dev/{self.emmc}p1", "uuid": ROOT_UUID, "partuuid": EMMC_PARTUUID,
                                             "label": "armbi_emmc"}]}]}), "")
        if program == "blkid" and "-t" in cmd:
            device = self.tagged.get(cmd[cmd.index("-t") + 1])
            return host.HostResult(0, f"{device}\n", "") if device else host.HostResult(2, "", "")
        if program == "timeout" and "fsck.ext4" in cmd:
            # A read-only check (-n) of the eMMC's root; -f checks a clean one too.
            inner = cmd[cmd.index("fsck.ext4"):]
            assert "-n" in inner and "-y" not in inner and "-p" not in inner, inner
            status, output = self.fsck.get(" ".join(inner[1:-1]), (0, f"{inner[-1]}: clean, 61234/7618560 files\n"))
            return host.HostResult(status, output, "")
        if program == "blkid":
            uuid = self.uuids.get(cmd[-1])
            # While udev re-reads the table of a card with nothing mounted after a write to the whole
            # card, its partitions are gone for a moment: blkid finds none. (With a partition mounted,
            # udev cannot re-read the table and only probes the partitions again.)
            if self.udev_probing and not self.mounted & {BOOT_DIR, CARD_DIR} and cmd[-1].startswith(f"/dev/{self.card}p"):
                uuid = None
            return host.HostResult(0, f"{uuid}\n", "") if uuid else host.HostResult(2, "", "")
        if program == "ls":
            return self._ls(cmd[-1])
        if program == "mountpoint":
            return ok if cmd[-1] in self.mounted else fail
        if program == "systemctl" and cmd[1] == "show":
            return host.HostResult(0, f"{self.return_unit}\n", "")
        if program == "systemctl" and cmd[1] == "is-enabled":
            return ok if cmd[-1] in self.enabled else fail
        if program == "btrfs":
            return self._btrfs(cmd)
        if program == "rsync":
            return self._rsync(cmd)
        # Everything else changes the host.
        self._change(cmd)
        if input is not None:
            self.inputs[shlex.join(cmd)] = input
        if program == "udevadm" and cmd[1] == "settle":
            self.udev_probing = False  # udev's work is done, also when the test makes the command fail
        if any(shlex.join(cmd).startswith(prefix) for prefix in self.failing):
            return host.HostResult(1, "", f"{program}: an I/O error\n")
        # wipefs opens its target exclusively: while udev probes the card (after a write that closed it,
        # or the unmount of one of its filesystems) the open fails, as Remove found on the W3 right after
        # its unmounts (2026-11-24).
        if program == "wipefs" and cmd[-1].startswith(f"/dev/{self.card}") and (self.udev_probing or self.busy_wipes):
            self.busy_wipes = max(0, self.busy_wipes - 1)
            return host.HostResult(1, "", f"wipefs: error: {cmd[-1]}: probing initialization failed: Device or resource busy\n")
        # A write to the card that closes it makes udev probe it (and re-read its table) through its
        # watch: until udevadm settle, the kernel finds the card busy at blockdev --rereadpt, as Set up
        # found on the F3 after the loader's writes (2026-11-24).
        if program in ("dd", "wipefs", "sfdisk") and any(
                part.startswith((f"/dev/{self.card}", f"of=/dev/{self.card}")) for part in cmd):
            self.udev_probing = True
        elif program == "udevadm" and cmd[1] == "settle":
            self.udev_probing = False
        elif program == "blockdev" and "--rereadpt" in cmd and (self.udev_probing or self.busy_rereads):
            self.busy_rereads = max(0, self.busy_rereads - 1)
            return host.HostResult(1, "", "blockdev: ioctl error on BLKRRPART: Device or resource busy\n")
        if program == "mount":
            self.mounted.add(cmd[1])
            self.files.update(self.hidden.pop(cmd[1], {}))
        elif program == "umount":
            if cmd[1] in (BOOT_DIR, CARD_DIR):
                self.udev_probing = True
            # What the card's filesystem holds is no more under its mount point.
            self.mounted.discard(cmd[1])
            inside = {name: text for name, text in self.files.items() if name.startswith(cmd[1] + "/")}
            self.hidden[cmd[1]] = inside
            for name in inside:
                del self.files[name]
            self.dirs -= {name for name in self.dirs if name.startswith(cmd[1] + "/")}
        elif program == "mv":
            self.files[cmd[-1]] = self.files.pop(cmd[-2])
        elif program == "rm":
            for path in cmd[cmd.index("--") + 1:] if "--" in cmd else cmd[2:]:
                self.files.pop(path, None)
                self.dirs.discard(path)
                for name in [name for name in self.files if name.startswith(path + "/")]:
                    del self.files[name]
        elif program == "mkdir":
            for part in cmd[1:]:
                while part.startswith("/") and part != "/":  # with -p, its parents too
                    self.dirs.add(part)
                    part = part.rsplit("/", 1)[0] or "/"
        elif program == "rmdir":
            for path in [part for part in cmd[1:] if part.startswith("/")]:
                inside = [name for name in [*self.files, *self.dirs] if name.startswith(path + "/")]
                if inside and "--ignore-fail-on-non-empty" not in cmd:
                    return host.HostResult(1, "", f"rmdir: failed to remove '{path}': Directory not empty\n")
                if not inside:
                    self.dirs.discard(path)
        elif program == "dd" and input is not None:
            seek = next((int(part[5:]) for part in cmd if part.startswith("seek=")), 0)
            size = int(next(part[3:] for part in cmd if part.startswith("bs=")))
            data = input.encode("utf-8", "surrogateescape")
            if size == 512:
                self.sectors[seek] = data.ljust(512, b"\0")
            else:
                self.raw[seek * size] = data[:size]
        elif program == "dd" and "if=/dev/zero" in cmd and f"of=/dev/{self.card}" in cmd:
            # Zeros over the card: what dd wrote there before is gone.
            options = dict(part.split("=", 1) for part in cmd[1:] if "=" in part)
            size = {"1M": 1024 * 1024}.get(options["bs"]) or int(options["bs"])
            start = int(options.get("seek", 0)) * size
            end = start + int(options["count"]) * size
            self.raw = {at: data for at, data in self.raw.items() if at + len(data) <= start or at >= end}
            self.sectors = {sector: data for sector, data in self.sectors.items()
                            if not start <= sector * 512 < end}
        elif program == "wipefs" and cmd[-1].startswith(f"/dev/{self.card}"):
            # The signatures of one of the card's filesystems, whose label and files go with them, or of its
            # table: then lsblk finds none of UNOS's labels.
            filesystems = {f"/dev/{self.card}p1": ("UNOS-BOOT", BOOT_DIR), f"/dev/{self.card}p2": ("UNOS-STANDBY", CARD_DIR)}
            label, folder = filesystems.get(cmd[-1], (None, None))
            labels = tuple(name for name in self.cards[0].labels if label is not None and name != label)
            for gone in [folder] if folder else [BOOT_DIR, CARD_DIR]:
                self.hidden.pop(gone, None)
            self.cards = [replace(self.cards[0], labels=labels, use=self.cards[0].use if labels else None,
                                  uuids=self.cards[0].uuids if labels else frozenset())]
        elif program == "mkfs.vfat":
            self.uuids[cmd[-1]] = BOOT_UUID
            self.hidden.pop(BOOT_DIR, None)
        elif program == "mkfs.btrfs":
            self.hidden.pop(CARD_DIR, None)
            self.uuids[cmd[-1]] = CARD_UUID
            self.block_devices |= {f"/dev/{self.card}p1", f"/dev/{self.card}p2"}
            self.cards = [replace(self.cards[0], labels=("UNOS-BOOT", "UNOS-STANDBY"), use="The SD card standby")]
        elif program == "systemctl" and cmd[1] == "reboot":
            self.reboots += 1
        elif program == "systemctl" and cmd[1] in ("enable", "disable"):
            names = {part for part in cmd[2:] if not part.startswith("-")}
            self.enabled = self.enabled | names if cmd[1] == "enable" else self.enabled - names
        elif program in ("bash", "dd", "wipefs", "sfdisk", "blockdev", "udevadm", "chattr", "chmod", "ln", "sync",
                         "systemctl"):
            if program == "bash" and "docker save" in cmd[2]:
                self.files[cmd[-1]] = "archive"
                return host.HostResult(self.copy_status.get(f"image:{cmd[-2]}", 0), "", "")
        else:
            raise AssertionError(f"a command the fake host does not know: {cmd}")
        return ok

    def _docker(self, cmd: list[str]) -> host.HostResult:
        if cmd[1] == "info":
            return host.HostResult(0, f"{self.docker_root}\n", "")
        if cmd[1] == "inspect":
            containers = [
                {"Name": "/unos-supervisor", "Config": {"Image": "deploy-supervisor", "Labels": {
                    "com.docker.compose.project": "deploy", "com.docker.compose.project.working_dir": WORKDIR,
                    "com.docker.compose.service": "supervisor"}}},
                {"Name": "/unos-webui", "Config": {"Image": "deploy-webui", "Labels": {
                    "com.docker.compose.project": "deploy", "com.docker.compose.project.working_dir": WORKDIR,
                    "com.docker.compose.service": "webui"}}},
            ]
            return host.HostResult(0, json.dumps(containers), "")
        if cmd[1:3] == ["image", "inspect"] and cmd[-1].startswith("sha256:"):
            # Whether the card's Docker has an image of a critical app (ADR-0500).
            return host.HostResult(0 if cmd[-1] in self.loaded_images else 1, "", "")
        if cmd[1:3] == ["image", "inspect"]:
            return host.HostResult(0, self.images[cmd[-1]] + "\n", "")
        if cmd[1] == "load":
            self._change(cmd)
            self.loaded_images.add("sha256:" + cmd[-1].rsplit("/", 1)[1].removesuffix(".tar.gz"))
            return host.HostResult(0, "", "")
        if cmd[1:3] == ["volume", "ls"]:
            return host.HostResult(0, "".join(f"{name}\n" for name in self.volumes), "")
        if cmd[1:3] == ["volume", "inspect"]:
            return host.HostResult(0, self.volumes[cmd[-1]] + "\n", "")
        raise AssertionError(f"a docker command the fake host does not know: {cmd}")

    def _ls(self, path: str) -> host.HostResult:
        if path == CARD_DIR:
            names = [f"@sys-{number}" for number in self.subvolumes] + ["state.json"] + sorted(
                p.rsplit("/", 1)[1] for p in self.subvolume_paths if p.startswith(CARD_DIR + "/"))
        else:
            prefix = path.rstrip("/") + "/"
            names = sorted({name[len(prefix):].split("/")[0] for name in [*self.files, *self.dirs]
                            if name.startswith(prefix)})
        return host.HostResult(0, "".join(f"{name}\n" for name in names), "")

    def _btrfs(self, cmd: list[str]) -> host.HostResult:
        if "@sys-" not in cmd[-1]:
            return self._other_subvolume(cmd)
        if cmd[1] == "inspect-internal":
            number = int(cmd[-1].rsplit("@sys-", 1)[1])
            return host.HostResult(0, f"{self.subvolumes[number]}\n", "")
        self._change(cmd)
        number = int(cmd[-1].rsplit("@sys-", 1)[1])
        if cmd[2] in ("create", "snapshot"):
            self.subvolumes[number] = self.next_subvolume_id
            self.next_subvolume_id += 1
            if cmd[2] == "snapshot":
                source = int(cmd[3].rsplit("@sys-", 1)[1])
                for name in [name for name in self.files if name.startswith(f"{CARD_DIR}/@sys-{source}/")]:
                    self.files[name.replace(f"@sys-{source}/", f"@sys-{number}/", 1)] = self.files[name]
        elif cmd[2] == "delete":
            self.subvolumes.pop(number, None)
            for name in [name for name in self.files if name.startswith(f"{CARD_DIR}/@sys-{number}/")]:
                del self.files[name]
        return host.HostResult(0, "", "")

    def _other_subvolume(self, cmd: list[str]) -> host.HostResult:
        """A subvolume of a pool or an app's copy on the card: its files are those under its path."""
        self._change(cmd)
        if any(shlex.join(cmd).startswith(prefix) for prefix in self.failing):
            return host.HostResult(1, "", "btrfs: an I/O error\n")
        target = cmd[-1]
        if cmd[2] == "create":
            self.subvolume_paths.add(target)
            self.dirs.add(target)
        elif cmd[2] == "snapshot":
            source = cmd[-2]
            self.subvolume_paths.add(target)
            self.dirs.add(target)
            for name in [name for name in self.files if name.startswith(source + "/") and not name.startswith(target + "/")]:
                self.files[target + name[len(source):]] = self.files[name]
                if name in self.file_sizes:
                    self.file_sizes[target + name[len(source):]] = self.file_sizes[name]
            for name in [name for name in self.dirs if name.startswith(source + "/") and not name.startswith(target + "/")]:
                self.dirs.add(target + name[len(source):])
        elif cmd[2] == "delete":
            if target not in self.subvolume_paths:
                return host.HostResult(1, "", f"ERROR: Could not statfs: {target}\n")
            self.subvolume_paths.discard(target)
            self.dirs = {name for name in self.dirs if name != target and not name.startswith(target + "/")}
            for name in [name for name in self.files if name.startswith(target + "/")]:
                del self.files[name]
        return host.HostResult(0, "", "")

    def size_of(self, path: str, excludes: list[str]) -> int | None:
        """What du -sb counts under ``path``: its files' sizes, without what an exclude matches (a basename
        pattern *suffix at any depth, or a full path)."""
        if not self.exists(path) and not any(name.startswith(path + "/") for name in self.files):
            return None

        def left_out(name: str) -> bool:
            parts = name.split("/")
            for pattern in excludes:
                if pattern.startswith("*") and any(part.endswith(pattern[1:]) for part in parts):
                    return True
                if name == pattern or name.startswith(pattern + "/"):
                    return True
            return False

        return sum(self.file_sizes.get(name, len(text)) for name, text in self.files.items()
                   if (name == path or name.startswith(path + "/")) and not left_out(name))

    def _app_rsync(self, cmd: list[str], source: str, destination: str) -> host.HostResult:
        """rsync of an app's folder to its copy on the card, with its excludes (*suffix anywhere, /relative
        anchored) and --delete; a dry run answers ``compare["app:<app>"]``."""
        app = destination.split("/@app-", 1)[1].split("/", 1)[0].rsplit("-", 1)[0]
        if "--dry-run" in cmd:
            return host.HostResult(0, "".join(f"{line}\n" for line in self.compare.get(f"app:{app}", [])), "")
        self._change(cmd)
        status = self.copy_status.get(f"app:{app}", 0)
        if status:
            return host.HostResult(status, "", f"rsync error: some files vanished (code {status})\n")
        source, destination = source.rstrip("/"), destination.rstrip("/")
        excludes = [part[len("--exclude="):] for part in cmd if part.startswith("--exclude=")]

        def left_out(relative: str) -> bool:
            parts = relative.split("/")
            for pattern in excludes:
                if pattern.startswith("*") and any(part.endswith(pattern[1:]) for part in parts):
                    return True
                anchored = pattern.lstrip("/")
                if pattern.startswith("/") and (relative == anchored or relative.startswith(anchored + "/")):
                    return True
            return False

        copied = {}
        for name, text in self.files.items():
            if name.startswith(source + "/") and not left_out(name[len(source) + 1:]):
                copied[destination + name[len(source):]] = text
                if name in self.file_sizes:
                    self.file_sizes[destination + name[len(source):]] = self.file_sizes[name]
        for name in [name for name in self.files if name.startswith(destination + "/") and name not in copied]:
            del self.files[name]
        self.files.update(copied)
        self.dirs.add(destination)
        return host.HostResult(0, "", "")

    def _app_rsync_back(self, cmd: list[str], source: str, destination: str) -> host.HostResult:
        """rsync of an app's run copy back to its folder on the pool (system.sd-standby-failback), with its
        excludes, --delete and --backup-dir: each file it replaces or deletes moves into the backup folder; a
        dry run with --stats answers the bytes it would transfer. ``copy_status["back:<app>"]`` fails it."""
        app = source.split("/@app-", 1)[1].split("/", 1)[0].rsplit("-", 1)[0]
        source, destination = source.rstrip("/"), destination.rstrip("/")
        excludes = [part[len("--exclude="):] for part in cmd if part.startswith("--exclude=")]

        def left_out(relative: str) -> bool:
            parts = relative.split("/")
            for pattern in excludes:
                if pattern.startswith("*") and any(part.endswith(pattern[1:]) for part in parts):
                    return True
                anchored = pattern.lstrip("/")
                if pattern.startswith("/") and (relative == anchored or relative.startswith(anchored + "/")):
                    return True
            return False

        wanted = {name[len(source) + 1:]: text for name, text in self.files.items()
                  if name.startswith(source + "/") and not left_out(name[len(source) + 1:])}
        have = {name[len(destination) + 1:]: text for name, text in self.files.items()
                if name.startswith(destination + "/") and not left_out(name[len(destination) + 1:])}
        changed = [relative for relative, text in wanted.items() if have.get(relative) != text]
        gone = [relative for relative in have if relative not in wanted]
        size = sum(self.file_sizes.get(f"{source}/{relative}", len(wanted[relative])) for relative in changed)
        if "--dry-run" in cmd:
            return host.HostResult(0, f"Number of files: {len(wanted)}\nTotal transferred file size: {size:,} bytes\n", "")
        self._change(cmd)
        status = self.copy_status.get(f"back:{app}", 0)
        if status:
            return host.HostResult(status, "", f"rsync: write failed: No space left on device (28)\nrsync error (code {status})\n")
        backup = next(part[len("--backup-dir="):] for part in cmd if part.startswith("--backup-dir="))
        for relative in [*changed, *gone]:
            if relative in have:
                self.files[f"{backup}/{relative}"] = self.files.pop(f"{destination}/{relative}")
        for relative in changed:
            self.files[f"{destination}/{relative}"] = wanted[relative]
        self.dirs.add(destination)
        return host.HostResult(0, f"Total transferred file size: {size:,} bytes\n", "")

    def _rsync(self, cmd: list[str]) -> host.HostResult:
        destination = cmd[-1]
        if "/@app-" in cmd[-2] and "/@app-" not in destination:
            return self._app_rsync_back(cmd, cmd[-2], destination)
        if "/@app-" in destination:
            return self._app_rsync(cmd, cmd[-2], destination)
        if destination.endswith("/unos.db"):
            part = "database"
        elif "/volumes/" in destination:
            part = "volume:" + destination.rstrip("/").rsplit("/", 1)[1]
        elif destination.startswith(BOOT_DIR):
            part = "boot"
        else:
            part = "system"
        if "--dry-run" in cmd:
            excluded = [part[len("--exclude="):] for part in cmd if part.startswith("--exclude=")]
            found = [line for line in self.compare.get(part, []) if not _excluded(line.split(None, 1)[-1], excluded)
                     # rsync names no folder whose time alone differs with --omit-dir-times.
                     and not ("--omit-dir-times" in cmd and line.startswith(".d..t......"))]
            return host.HostResult(0, "".join(f"{line}\n" for line in found), "")
        self._change(cmd)
        status = self.copy_status.get(part, 0)
        return host.HostResult(status, "", "" if status == 0 else f"rsync error: some files vanished (code {status})\n")



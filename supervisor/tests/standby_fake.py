def _excluded(path: str, patterns: list[str]) -> bool:
    """Whether rsync leaves out ``path`` (relative to the transfer's root) for one of its --exclude
    patterns: anchored ones (/var/log*), as rsync matches them, enough for the standby's patterns."""
    path = path.rstrip("/")
    for pattern in patterns:
        anchored = pattern.lstrip("/").rstrip("/")
        if anchored.endswith("*"):
            if path.startswith(anchored[:-1]):
                return True
        elif path == anchored or path.startswith(anchored + "/"):
            return True
    return False


def stopped_at_each_step(make, run) -> list[StandbyFakeHost]:
    """``run`` on a fresh fake from ``make`` once to the end, then once stopped before each of its changes:
    the fakes as each stop left them."""
    whole = make()
    run()
    stopped = []
    for step in range(len(whole.changes)):
        fake = make()
        fake.cut_at = step
        with pytest.raises(PowerCut):
            run()
        fake.cut_at = None
        stopped.append(fake)
    return stopped


def install(monkeypatch, fake: StandbyFakeHost) -> StandbyFakeHost:
    monkeypatch.setattr(host, "run_on_host", fake.run)
    monkeypatch.setattr(conditions, "read_cards", fake.read_cards)
    monkeypatch.setattr(host, "block_device_attribute",
                        lambda name, attribute: fake.sectors_written() if attribute == "stat" else None)
    return fake

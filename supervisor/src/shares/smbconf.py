@dataclass
class SectionValues:
    """The effective share options of one section: section value, else [global], else Samba's default."""

    path: str | None = None
    comment: str = ""
    browseable: bool = True
    read_only: bool = True
    guest_ok: bool = False
    guest_only: bool = False
    available: bool = True
    printable: bool = False
    valid_users: list[str] = field(default_factory=list)
    invalid_users: list[str] = field(default_factory=list)
    read_list: list[str] = field(default_factory=list)
    write_list: list[str] = field(default_factory=list)
    admin_users: list[str] = field(default_factory=list)
    hosts_allow: str = ""
    hosts_deny: str = ""
    smb_encrypt: str = ""
    copy: str = ""
    # Canonical ownership key -> the option that sets it.
    ownership: dict[str, ParsedOption] = field(default_factory=dict)
    # Attribute name (e.g. "read_only", "hosts_allow") -> the option that set the effective value.
    source: dict[str, ParsedOption] = field(default_factory=dict)
    # Attribute names set by the section itself (not inherited from [global]).
    from_section: set[str] = field(default_factory=set)
    # Options whose value is not a boolean (read with BOOLEAN_FAIL_SAFE).
    invalid_booleans: list[ParsedOption] = field(default_factory=list)

    @property
    def encryption_required(self) -> bool:
        return normalize_key(self.smb_encrypt) in ENCRYPTION_REQUIRED


def _apply(values: SectionValues, option: ParsedOption, in_section: bool) -> None:
    key = option.key
    if key in _BOOLEAN_KEYS:
        attribute, inverted = _BOOLEAN_KEYS[key]
        parsed = parse_bool(option.value)
        if parsed is None:
            values.invalid_booleans.append(option)
            result = BOOLEAN_FAIL_SAFE[attribute]
        else:
            result = (not parsed) if inverted else parsed
        setattr(values, attribute, result)
    elif key in _TEXT_KEYS:
        attribute = _TEXT_KEYS[key]
        setattr(values, attribute, option.value)
    elif key in _LIST_KEYS:
        attribute = _LIST_KEYS[key]
        setattr(values, attribute, split_list(option.value))
    elif key in OWNERSHIP_KEYS:
        attribute = OWNERSHIP_KEYS[key]
        values.ownership[attribute] = option
    else:
        return
    values.source[attribute] = option
    if in_section:
        values.from_section.add(attribute)


def _considered_globals(
    parsed: ParsedSmbConf, ignore_unos_globals: bool, count: int | None = None
) -> list[ParsedOption]:
    """The [global] options (the first ``count`` of them when given), without UNOS's own
    lines in a file that starts with HEADER when ``ignore_unos_globals``."""
    options = parsed.global_options if count is None else parsed.global_options[:count]
    if not (ignore_unos_globals and parsed.unos_header):
        return list(options)
    return [o for o in options if not is_unos_global_line(o)]


def section_values(
    parsed: ParsedSmbConf, section: ParsedSection | None, *, ignore_unos_globals: bool = True
) -> SectionValues:
    """Effective values of ``section`` (None: the [global] values alone), in file order with
    the inversion of writeable applied, so ``read only = no`` then ``writable = no`` is read-only.

    A section inherits only the [global] options written before its first
    header, as in Samba, which copies the share defaults when a section
    starts: a [global] block after a share changes the shares that follow it,
    not that share. With ``section`` None, every [global] option counts: the
    final [global] values, which smbd uses for its global checks (hosts allow
    and hosts deny of every connection).

    In a file that starts with HEADER, [global] lines equal to a line of either
    render_global variant are UNOS's own (``invalid users = root``, ``hosts
    allow``): they restrict nothing that UNOS does not render itself, so they
    are left out unless ``ignore_unos_globals`` is False.
    """
    values = SectionValues()
    count = section.global_count if section is not None else None
    for option in _considered_globals(parsed, ignore_unos_globals, count):
        _apply(values, option, False)
    for option in section.options if section is not None else ():
        _apply(values, option, True)
    return values


def global_options_considered(parsed: ParsedSmbConf) -> list[ParsedOption]:
    """The [global] options of a file, without UNOS's own lines when it starts with HEADER."""
    return _considered_globals(parsed, True)


def _values_of(option: ParsedOption) -> SectionValues:
    values = SectionValues()
    _apply(values, option, False)
    return values


def _restricts(option: ParsedOption) -> bool:
    values = _values_of(option)
    return bool(values.hosts_allow or values.hosts_deny or values.invalid_users)


def global_restrictions(parsed: ParsedSmbConf) -> list[ParsedOption]:
    """The [global] options that remove all access at the import (ADR-0380), in file order:
    ``hosts allow``, ``hosts deny`` or an ``invalid users`` entry. Scripts that refuse
    connections are pairs of options: global_script_restrictions. Required encryption is
    the shares' option instead (global_encryption, ADR-0380).

    Every [global] block counts, not only the last value of an option: Samba
    copies the share defaults when a section starts (loadparm.c lp_do_section),
    so a restriction that a later block lifts still applies to the shares
    between the two blocks. UNOS's own lines of a file that starts with HEADER
    are not restrictions.
    """
    return [option for option in global_options_considered(parsed) if _restricts(option)]


def global_encryption(parsed: ParsedSmbConf) -> list[ParsedOption]:
    """The [global] options that require encryption, in file order: ``smb encrypt`` or ``server
    smb encrypt`` set to required, mandatory, force, forced or enforced. At the import every
    share then requires encryption (ADR-0380); every [global] block counts, as in
    global_restrictions."""
    return [option for option in global_options_considered(parsed) if _values_of(option).encryption_required]


@dataclass(frozen=True)
class ScriptRestriction:
    """A script whose failure refuses a connection: its command and its close option set to true."""

    command: ParsedOption   # preexec, exec or root preexec, not empty
    close: ParsedOption     # preexec close or root preexec close


def _set_script_option(scripts: dict[str, dict[str, ParsedOption]], option: ParsedOption) -> bool:
    """Record ``option`` when it is the command or close option of a script; whether it is one."""
    known = _SCRIPT_KEYS.get(option.key)
    if known is None:
        return False
    script, part = known
    scripts.setdefault(script, {})[part] = option
    return True


def _restricting(scripts: Mapping[str, Mapping[str, ParsedOption]]) -> list[ScriptRestriction]:
    found = []
    for parts in scripts.values():
        command, close = parts.get("command"), parts.get("close")
        # A close value that is not a boolean is read as the safer choice: true.
        if command is not None and close is not None and command.value and parse_bool(close.value) is not False:
            found.append(ScriptRestriction(command=command, close=close))
    return found


def section_script_restrictions(parsed: ParsedSmbConf, section: ParsedSection) -> list[ScriptRestriction]:
    """The scripts that can refuse connections to ``section`` (ADR-0380): with its effective
    values (the [global] options before its first header, then its own options, the last
    value of each), a command is set and its close option is true. The caller tells apart
    the restrictions that the section sets itself."""
    scripts: dict[str, dict[str, ParsedOption]] = {}
    for option in (*_considered_globals(parsed, True, section.global_count), *section.options):
        _set_script_option(scripts, option)
    return _restricting(scripts)


def global_script_restrictions(parsed: ParsedSmbConf) -> list[ScriptRestriction]:
    """The scripts of [global] that can refuse connections to every share, in the order they
    form. As in global_restrictions, every point of every [global] block counts: a pair
    that a later line undoes still applies to the shares written in between."""
    found: list[ScriptRestriction] = []
    scripts: dict[str, dict[str, ParsedOption]] = {}
    for option in global_options_considered(parsed):
        if not _set_script_option(scripts, option):
            continue
        for restriction in _restricting(scripts):
            if restriction not in found:
                found.append(restriction)
    return found


def _unos_global_lines() -> frozenset[tuple[str, str]]:
    lines: set[tuple[str, str]] = set()
    for guest_enabled in (False, True):
        for key, value in global_settings(guest_enabled, time_machine=True, interfaces=()):
            lines.add((normalize_key(key), value))
    return frozenset(lines)


_UNOS_GLOBAL_LINES = _unos_global_lines()
_INTERFACES_KEY = normalize_key("interfaces")
_LISTEN_KEYS = (_INTERFACES_KEY, normalize_key("bind interfaces only"))


def _is_unos_interfaces(value: str) -> bool:
    """An ``interfaces`` value as _listen_settings writes it: lo, then valid names, sorted, once each."""
    first, *names = value.split(" ")
    return first == LOOPBACK and all(is_bindable_name(name) for name in names) and names == sorted(set(names))


_UNOS_SHARE_LINES = frozenset((normalize_key(key), value) for key, value in _FIXED_SHARE_LINES)


def is_unos_global_line(option: ParsedOption) -> bool:
    """A [global] line equal to a line of a render_global variant (an ``interfaces`` line with any
    choice of interfaces, ADR-0391)."""
    if option.key == _INTERFACES_KEY:
        return _is_unos_interfaces(option.value)
    return (option.key, option.value) in _UNOS_GLOBAL_LINES


def listen_lines(text: str) -> tuple[str | None, str | None]:
    """The last values of ``interfaces`` and ``bind interfaces only`` in the [global] of ``text``
    (None for a line it lacks). smbd binds its addresses only when it starts, so a file whose values
    differ from the installed one's needs a restart of smbd, not a reload (ADR-0391)."""
    values: dict[str, str] = {}
    for option in parse_smb_conf(text).global_options:
        if option.key in _LISTEN_KEYS:
            values[option.key] = option.value
    return values.get(_LISTEN_KEYS[0]), values.get(_LISTEN_KEYS[1])


def is_unos_share_line(option: ParsedOption) -> bool:
    """One of the fixed lines that end every share section (_FIXED_SHARE_LINES)."""
    return (option.key, option.value) in _UNOS_SHARE_LINES


def _unos_option_lines() -> frozenset[tuple[str, str]]:
    """The option lines of _option_lines with a fixed value (normalized key, value): each vfs
    objects line it composes, Time Machine's line and the snapshots' lines."""
    lines = {
        (normalize_key("vfs objects"), " ".join((*fruit, *snapshots)))
        for fruit in ((), FRUIT_MODULES)
        for snapshots in ((), SNAPSHOT_MODULES)
    }
    lines.add((normalize_key("fruit:time machine"), "yes"))
    lines.update((normalize_key(key), value) for key, value in _SNAPSHOT_LINES)
    return frozenset(lines)


_UNOS_OPTION_LINES = _unos_option_lines()
_SNAPSHOT_MOUNTPOINT_KEY = normalize_key("shadow:mountpoint")


def is_unos_option_line(option: ParsedOption) -> bool:
    """A line that _option_lines renders for a share's protocol options (ADR-0380):
    shadow:mountpoint with any path, the other lines with their values."""
    return option.key == _SNAPSHOT_MOUNTPOINT_KEY or (option.key, option.value) in _UNOS_OPTION_LINES


VFS_OBJECTS_KEYS = frozenset({normalize_key("vfs objects"), normalize_key("vfs object")})
TIME_MACHINE_KEY = normalize_key("fruit:time machine")
_SNAPSHOT_KEY_PREFIX = "shadow:"


def _options_of(parsed: ParsedSmbConf, section: ParsedSection) -> tuple[ParsedOption, ...]:
    """The options that apply to ``section`` in file order: the [global] options before its first
    header (without UNOS's own lines in a file that starts with HEADER), then its own."""
    return (*_considered_globals(parsed, True, section.global_count), *section.options)


def vfs_objects(parsed: ParsedSmbConf, section: ParsedSection) -> ParsedOption | None:
    """The ``vfs objects`` line that applies to ``section``: its own last one, else the last one of
    [global] before it; None without one."""
    found = None
    for option in _options_of(parsed, section):
        if option.key in VFS_OBJECTS_KEYS:
            found = option
    return found


def last_option(parsed: ParsedSmbConf, section: ParsedSection, key: str) -> ParsedOption | None:
    """The last option of ``key`` (normalized) that applies to ``section``, or None."""
    found = None
    for option in _options_of(parsed, section):
        if option.key == key:
            found = option
    return found


def _snapshot_settings(parsed: ParsedSmbConf, section: ParsedSection) -> tuple[tuple[str, str], ...] | None:
    """What a tree connect of ``section`` lists as snapshots: the ``shadow:`` settings when its vfs
    modules include shadow_copy2, which reads them at the tree connect; None without it."""
    vfs = vfs_objects(parsed, section)
    if vfs is None or "shadow_copy2" not in split_list(vfs.value):
        return None
    settings = {option.key: option.value for option in _options_of(parsed, section)
                if option.key.startswith(_SNAPSHOT_KEY_PREFIX)}
    return tuple(sorted(settings.items()))


def is_unos_section(section: ParsedSection) -> bool:
    """Whether a section has the six fixed lines of _FIXED_SHARE_LINES (UNOS rendered it)."""
    present = {(option.key, option.value) for option in section.options}
    return _UNOS_SHARE_LINES <= present


# --- grants and shrinks (ADR-0103) ------------------------------------------------------


@dataclass(frozen=True)
class ShareGrants:
    name: str                               # the section name as written
    path: str | None
    grants: Mapping[str, int]               # principal -> READ or WRITE; see GUEST and ANY_USER
    unknown: bool                           # UNOS cannot evaluate the access exactly
    text: tuple[tuple[str, str], ...]       # the section's own options (key, value)
    encryption_required: bool = False       # a client that cannot encrypt is refused (ADR-0380)
    # The shadow: settings of a section that loads shadow_copy2 (Previous Versions, ADR-0380); None: none.
    snapshots: tuple[tuple[str, str], ...] | None = None


def _not_exact(values: SectionValues) -> bool:
    """Options whose effect on access UNOS cannot evaluate exactly (ADR-0103)."""
    return bool(
        values.copy
        or values.hosts_allow
        or values.hosts_deny
        or values.invalid_users
        or values.admin_users
        or ("forceuser" in values.ownership and values.ownership["forceuser"].value)
        or values.guest_only
        or any(
            is_group_or_variable(entry)
            for entry in (*values.valid_users, *values.read_list, *values.write_list)
        )
    )


def config_grants(parsed: ParsedSmbConf) -> dict[str, ShareGrants]:
    """The grants of each section of a file, keyed by its lower-case name (ADR-0103).

    Principals are user names (lower case), GUEST and ANY_USER (any
    authenticated user); 1 is read, 2 is write. Grants come from the
    section's effective values (the [global] options before its first
    header). A section is ``unknown`` when its effective values have an
    option of _not_exact, or when the [global] values of the whole file do:
    smbd checks the final [global] hosts allow and hosts deny for every
    connection, and an unknown section is only closed more often.
    """
    every_global_unknown = _not_exact(section_values(parsed, None))
    result: dict[str, ShareGrants] = {}
    for section in parsed.sections:
        values = section_values(parsed, section)
        grants: dict[str, int] = {}
        if values.available:
            level = READ if values.read_only else WRITE
            writers = {e.lower() for e in values.write_list if not is_group_or_variable(e)}
            users = [e.lower() for e in values.valid_users if not is_group_or_variable(e)]
            if not values.valid_users:
                if values.guest_ok:
                    grants[GUEST] = level
                grants[ANY_USER] = level
                for name in writers:
                    grants[name] = WRITE
            else:
                for name in users:
                    grants[name] = WRITE if (name in writers or not values.read_only) else READ
        unknown = parsed.has_include or every_global_unknown or _not_exact(values)
        result[section.name.lower()] = ShareGrants(
            name=section.name,
            path=values.path,
            grants=grants,
            unknown=unknown,
            text=tuple((option.key, option.value) for option in section.options),
            encryption_required=values.encryption_required,
            snapshots=_snapshot_settings(parsed, section),
        )
    return result


def _level(grants: Mapping[str, int], principal: str) -> int:
    level = grants.get(principal, 0)
    if principal not in (GUEST, ANY_USER):
        # Any authenticated user includes every named user.
        level = max(level, grants.get(ANY_USER, 0))
    return level


def shrunk_shares(old_text: str, new_text: str) -> list[str]:
    """Names (as in the old file) of the sections whose access shrank from ``old_text``
    to ``new_text`` (ADR-0103): removed, renamed or no longer served, path changed,
    an unknown section whose text changed, a principal that lost read or write,
    encryption required now, or snapshots listed before (shadow_copy2) and no longer
    or others (ADR-0380): a tree connect keeps what it was granted, also a session
    without encryption, and its vfs modules with their settings."""
    old = config_grants(parse_smb_conf(old_text))
    new = config_grants(parse_smb_conf(new_text))
    shrunk: list[str] = []
    for key, before in old.items():
        after = new.get(key)
        if (
            after is None
            or after.path != before.path
            or (before.unknown and after.text != before.text)
            or any(_level(after.grants, p) < level for p, level in before.grants.items())
            or (after.encryption_required and not before.encryption_required)
            or (before.snapshots is not None and after.snapshots != before.snapshots)
        ):
            shrunk.append(before.name)
    return shrunk


_AVAILABLE_KEY = normalize_key("available")


def time_machine_shares(text: str) -> set[str]:
    """The lower-case names of the sections of ``text`` that smbd announces to Time Machine with
    _adisk._tcp (ADR-0380): ``fruit:time machine`` true in a section that is available, as
    smbd's lp_snum_ok asks (a share without access has ``available = no``)."""
    found = set()
    for section in parse_smb_conf(text).sections:
        values = {key: [option.value for option in section.options if option.key == key]
                  for key in (TIME_MACHINE_KEY, _AVAILABLE_KEY)}
        offered = values[TIME_MACHINE_KEY] and parse_bool(values[TIME_MACHINE_KEY][-1])
        if offered and (not values[_AVAILABLE_KEY] or parse_bool(values[_AVAILABLE_KEY][-1]) is not False):
            found.add(section.name.lower())
    return found
